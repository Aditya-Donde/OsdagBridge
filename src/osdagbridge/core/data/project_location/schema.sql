-- Weather Database Schema (4 Tables: Parent + 3 Children)
-- Drop tables if they exist (drop children first, then parent)
DROP TABLE IF EXISTS windspeed_data;
DROP TABLE IF EXISTS zone_data;
DROP TABLE IF EXISTS temperature_data;
DROP TABLE IF EXISTS stations;

-- Table 1: Stations (Parent/Canonical Table)
-- This is the source of truth for all state-station combinations
CREATE TABLE stations (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    state VARCHAR(100) NOT NULL,
    station VARCHAR(100) NOT NULL,
    UNIQUE (state, station)
);

-- Table 2: Temperature Data (Child Table)
CREATE TABLE temperature_data (
    state VARCHAR(100) NOT NULL,
    station VARCHAR(100) NOT NULL,
    max_temp DECIMAL(5, 2),
    min_temp DECIMAL(5, 2),
    PRIMARY KEY (state, station)
);

-- Table 3: Zone Data (Child Table)
CREATE TABLE zone_data (
    state VARCHAR(100) NOT NULL,
    station VARCHAR(100) NOT NULL,
    zone VARCHAR(10) NOT NULL,
    z_value DECIMAL(4, 2) NOT NULL,
    PRIMARY KEY (state, station)
);

-- Table 4: Windspeed Data (Child Table)
CREATE TABLE windspeed_data (
    state VARCHAR(100) NOT NULL,
    station VARCHAR(100) NOT NULL,
    wind_speed INTEGER NOT NULL,
    PRIMARY KEY (state, station)
);

-- Create indexes for better query performance
CREATE INDEX idx_stations_state ON stations(state);
CREATE INDEX idx_stations_station ON stations(station);
CREATE INDEX idx_station_id ON stations(id);

